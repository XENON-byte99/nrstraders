#!/usr/bin/env python3
"""Build static/vendor/: local copies of everything the templates load from CDNs.

Run once before building the mobile app (the Android build does it for you):

    python mobile/build_offline_assets.py

Needs Node.js + npm. Everything comes from the npm registry, pinned to the
same versions the templates reference:

* Font Awesome, html2pdf.js, SheetJS, SortableJS, Lucide - copied as-is.
* Tailwind - compiled to one static CSS file from the classes the templates
  actually use (much faster on a phone than the in-browser CDN compiler).
* Google Fonts - the families/weights named in the templates, as local woff2.
"""
import html
import json
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path
from urllib.parse import parse_qsl, urlsplit

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from nrs_project.offline_assets import (  # noqa: E402
    GOOGLE_FONTS_LINK, NPM_ASSETS, TAILWIND_SAFELIST_COLOURS, TAILWIND_VERSION,
)

VENDOR = ROOT / 'static' / 'vendor'
NPM = shutil.which('npm') or 'npm'


def run(cmd, cwd):
    print('  $', ' '.join(str(c) for c in cmd))
    subprocess.run(cmd, cwd=cwd, check=True)


def npm_unpack(spec, work):
    """Download an npm package and return the extracted 'package' directory."""
    out = subprocess.run([NPM, 'pack', spec, '--silent'], cwd=work, check=True,
                         capture_output=True, text=True).stdout.strip().splitlines()[-1]
    dest = work / re.sub(r'[^A-Za-z0-9.]+', '_', spec)
    dest.mkdir()
    with tarfile.open(work / out) as tar:
        tar.extractall(dest, filter='data')
    return next(p for p in dest.iterdir() if p.is_dir())


def copy_npm_assets(work):
    for _prefix, spec, src, local, keep in NPM_ASSETS:
        print('->', spec)
        base = npm_unpack(spec, work) / src
        target = VENDOR / local
        count = 0
        for path in base.rglob('*'):
            rel = path.relative_to(base).as_posix()
            if path.is_file() and any(rel == k or (k.startswith('.') and rel.endswith(k)) for k in keep):
                (target / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, target / rel)
                count += 1
        if not count:
            raise SystemExit('nothing copied for %s' % spec)


def build_tailwind(work):
    print('-> tailwindcss@%s' % TAILWIND_VERSION)
    project = work / 'tw'
    project.mkdir()
    (project / 'package.json').write_text('{"private": true}')
    run([NPM, 'install', '--silent', '--no-audit', '--no-fund', 'tailwindcss@' + TAILWIND_VERSION], project)
    colours = '|'.join(TAILWIND_SAFELIST_COLOURS)
    (project / 'tailwind.config.js').write_text(
        'module.exports = {\n'
        '  content: %s,\n'
        '  safelist: [{ pattern: /^(bg|text|border|ring)-(%s)-(50|100|200|300|400|500|600|700|800)$/,'
        ' variants: ["hover"] }],\n'
        '};\n' % (json.dumps([str(ROOT / 'templates' / '**' / '*.html'),
                              str(ROOT / 'static' / 'js' / '**' / '*.js')]), colours))
    (project / 'in.css').write_text('@tailwind base;\n@tailwind components;\n@tailwind utilities;\n')
    run([str(project / 'node_modules' / '.bin' / 'tailwindcss'), '-c', 'tailwind.config.js',
         '-i', 'in.css', '-o', str(VENDOR / 'tailwind.css'), '--minify'], project)


def wanted_fonts():
    """{family: {(weight, style)}} from every Google Fonts link in the templates."""
    fonts = {}
    for template in (ROOT / 'templates').rglob('*.html'):
        for url in GOOGLE_FONTS_LINK.findall(template.read_text(encoding='utf-8')):
            for key, value in parse_qsl(urlsplit(html.unescape(url)).query):
                if key != 'family':
                    continue
                family, _, axes = value.partition(':')
                variants = fonts.setdefault(family.replace('+', ' '), set())
                if not axes:
                    variants.add((400, 'normal'))
                    continue
                names, _, tuples = axes.partition('@')
                names = names.split(',')
                for entry in tuples.split(';'):
                    values = dict(zip(names, entry.split(',')))
                    style = 'italic' if values.get('ital') == '1' else 'normal'
                    variants.add((int(values.get('wght', 400)), style))
    return fonts


def build_fonts(work):
    target = VENDOR / 'fonts'
    target.mkdir(parents=True, exist_ok=True)
    css = ['/* Generated by mobile/build_offline_assets.py */']
    for family, variants in sorted(wanted_fonts().items()):
        slug = family.lower().replace(' ', '-')
        print('-> @fontsource/%s' % slug)
        files = npm_unpack('@fontsource/' + slug, work) / 'files'
        for weight, style in sorted(variants):
            for subset in ('latin', 'latin-ext'):
                name = '%s-%s-%d-%s.woff2' % (slug, subset, weight, style)
                if not (files / name).exists():
                    if subset == 'latin':
                        print('   (no %d %s)' % (weight, style))
                    continue
                shutil.copyfile(files / name, target / name)
                unicode_range = ('U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,'
                                 'U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD' if subset == 'latin'
                                 else 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+1E00-1E9F,'
                                      'U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF')
                css.append("@font-face{font-family:'%s';font-style:%s;font-weight:%d;font-display:swap;"
                           "src:url(%s) format('woff2');unicode-range:%s}" % (family, style, weight, name, unicode_range))
    (target / 'fonts.css').write_text('\n'.join(css) + '\n')


def main():
    if VENDOR.exists():
        shutil.rmtree(VENDOR)
    VENDOR.mkdir(parents=True)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        copy_npm_assets(work)
        build_fonts(work)
        build_tailwind(work)
    size = sum(p.stat().st_size for p in VENDOR.rglob('*') if p.is_file())
    print('Done: %s (%.1f MB)' % (VENDOR, size / 1e6))


if __name__ == '__main__':
    main()
